/**
 * Vercel Serverless Function: Telegram Bot Webhook Handler
 * Path: /api/telegram
 *
 * How it works:
 * - Telegram sends POST requests to https://your-domain.vercel.app/api/telegram
 *   every time a user sends a message or clicks an inline button.
 * - This function processes the update and replies instantly.
 * - No long-polling needed on the server — Telegram pushes to us.
 *
 * The client-side (browser) bot is still used for:
 * - Automatic hazard alerts triggered by the physics simulation
 * - Fault injection notifications
 * These are sent directly from the browser since they depend on live
 * simulation state that only exists in the browser context.
 */

