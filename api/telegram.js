export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(200).json({ ok: true, message: 'PMS Telegram Webhook Active' });
  }

  try {
    const update = req.body;

    // Text messages
    if (update.message && update.message.text) {
      const text = update.message.text.trim();
      if (text.startsWith('/start'))       await handleStart();
      else if (text.startsWith('/status')) await handleStatus();
      else if (text.startsWith('/report')) await handleReport();
    }

    // Inline button callbacks
    if (update.callback_query) {
      const cb = update.callback_query.data;
      if (cb === 'cmd_status') await handleStatus();
      else if (cb === 'cmd_report') await handleReport();
      await answerCallback(update.callback_query.id);
    }

    return res.status(200).json({ ok: true });
  } catch (err) {
    console.error('[Webhook] Error:', err);
    return res.status(200).json({ ok: false });
  }
}
